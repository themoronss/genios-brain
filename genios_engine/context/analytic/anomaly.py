"""L2.4.8 · the ANOMALY DETECTOR (BLG-13) — is this node behaving unlike ITSELF?

Two units, one pipeline, the same shape the trend computer uses:

* **U1 `detect_anomaly`** — a series in, a typed `AnomalyVerdict` out. Pure: no database, no
  network, no clock, no model. Integer arithmetic end to end.
* **U2 `refresh_anomaly_facts`** — writes the verdict back as `derived.anomaly.<metric>` on the
  node so L3 and L4 read it like any other fact. Called from `context/runner.process_pending`,
  which is the sweep both API sync routes and the upload route already run.

**WHY THIS EXISTS BESIDE THE COHORT COMPARATOR.** A cohort answers *how does this account compare
to its peers*, and an account can sit in the top quartile of its cohort while collapsing against
its own six-month norm. That account is precisely the one a peer comparison never surfaces, and it
is the "at-risk flagged 30+ days early" case the product is sold on — the early signal comes from
a node's own baseline, not from the population.

**MAD, NOT STANDARD DEVIATION, AND THAT IS THE WHOLE DESIGN.** A standard deviation is defined by
squared error, so a single extreme reading widens the band in proportion to its own extremity —
the outlier inflates the dispersion until it sits inside it, which is exactly the reading an
anomaly detector exists to catch. A median absolute deviation moves by at most one rank when one
point moves arbitrarily far. `test_one_outlier_cannot_hide_inside_its_own_standard_deviation` is
the test that pins this: the same series, the same spike, sigma says "within 3σ" and MAD says
"22 MADs out".

**`z_like_bp` IS UNBOUNDED ON PURPOSE.** Doc 04 flags above 30000 — three times the top of the
0..10000 proportion range — so the contract validates it with `require_ratio_bp`, and nothing here
clamps it. A 40-MAD collapse must report as 40 MADs. A ceiling would render a catastrophe and a
bad Tuesday as the same number, which is the one thing the field is read for.

**BOTH CONDITIONS, ALWAYS** (`Z_LIKE_FLAG_BP` and `DEVIATION_FLAG_BP`). Statistically unusual is
not the same as materially large: a metric that normally sits at 2 going to 4 is many MADs out on
a series with almost no dispersion, and it is also nothing. The material floor is what stops the
detector filling a card with arithmetically impeccable trivia.

**SIX PERIODS OF BASELINE, ELSE A REFUSAL.** There is no anomaly without a normal to be anomalous
against, and `MIN_ANOMALY_PERIODS` is a CONTRACT rule (D-06) rather than a tunable here: `Anomaly`
itself refuses to be constructed with fewer. `INSUFFICIENT_HISTORY` is therefore a return value,
not an exception — a node with four months of data is not an error, it is a node we cannot say
this about yet, and the difference has to survive to the card.

**A GAP IS NOT A ZERO.** An unknown period is dropped from the baseline sample; it never
contributes a value and it is never interpolated. It reduces `periods_used`, which is what pushes
a sparse series toward `INSUFFICIENT_HISTORY` instead of toward a fabricated collapse. Doc 04
names "a coverage gap read as a drop" as the worst output this group can produce: a false churn
alarm about a real customer, generated by the tenant connecting one fewer mailbox.

**POINT-IN-TIME AND REPLAYABLE, ON BOTH SIDES OF THE PASS.** `eval_time` is a parameter with no
default and no fallback clock, every read is `as_at` that instant, and every number below is
integer arithmetic a reader can re-run by hand — so the same series at the same `eval_time` yields
a byte-identical verdict this morning, in September, and on a backfill.

And the WRITE is now point-in-time too, which it was not. U2 used to end its own upsert with
`valid_from = excluded.valid_from`, so September's sweep moved the window of March's row and
`read_graph(as_of=March)` answered "we knew nothing" about a verdict this module had published in
March. It publishes through `analytic/publish.publish_derived_fact` instead: `valid_from` never
moves, a verdict that has not changed writes nothing at all, and a verdict that changes in a later
week supersedes rather than overwrites. Doc 02's acceptance row — *replaying a March decision
against as_of=March reproduces its inputs* — is a property of this pass again.
"""

