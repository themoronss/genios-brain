# U2 · CHANGEPOINT DETECTION — "since March", not "declining"
# =================================================================================================

@dataclass(frozen=True)
class Changepoint:
    """The period a series changed direction, with both sides' trends as the receipt.

    `at` is a PERIOD boundary taken from the series itself, never a computed date: it is the
    `observed_at` of the first point of the later segment, so "since March" names a month that
    actually holds a reading. A changepoint whose period is a gap is not returned at all — see
    `find_changepoint`.
    """

    index: int
    at: datetime
    before: Trend
    after: Trend

    @property
    def turned(self) -> str:
        """The transition as a single readable token, e.g. `rising->declining`."""
        return f"{self.before.direction.value}->{self.after.direction.value}"


def find_changepoint(series: Sequence[MetricPoint], *,
                     min_points: int = MIN_TREND_POINTS) -> Changepoint | None:
    """Doc 04 U2 — the LONGEST suffix whose direction differs from the prefix's.

    Longest, so the split is scanned from the earliest legal index upward and the first qualifying
    one wins. That is what makes the answer *"since March"* rather than *"since last month"*: a
    decline that began in March also differs from the prefix when measured from June, and
    returning June would date the change to the last period the arithmetic still noticed it.

    Both segments are held to `min_points` and both must produce a real direction — a segment that
    returns `INSUFFICIENT_HISTORY` or `INSUFFICIENT_COVERAGE` cannot be one side of a claim that
    something changed, because we do not know what it was before. And the split period itself must
    be KNOWN: dating a change to a month we have no reading for is the gap-as-observation fault
    wearing a calendar.

    Returns `None` when nothing qualifies, which is the ordinary case and not a failure.
    """
    points = tuple(series)
    for split in range(min_points, len(points) - min_points + 1):
        if not points[split].known:
            continue
        before = compute_trend(points[:split], min_points=min_points)
        if before.direction in NON_ANSWERS:
            continue
        after = compute_trend(points[split:], min_points=min_points)
        if after.direction in NON_ANSWERS or after.direction is before.direction:
            continue
        return Changepoint(index=split, at=points[split].observed_at, before=before, after=after)
    return None


