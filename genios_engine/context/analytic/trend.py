def _known_pairs(series: Sequence[MetricPoint]) -> list[tuple[int, int]]:
    """`(period_index, value)` for every point that carries a reading.

    The index is the position in the DENSE series, not the position among the known points. That
    distinction is the whole gap discipline in one line: a reading two periods after its
    predecessor is plotted two units along, so a hole widens the spacing instead of vanishing and
    pulling the later readings backwards into a steeper slope.
    """
    return [(index, point.value_bp) for index, point in enumerate(series)
            if point.known and point.value_bp is not None]


def _ls_slope_scaled(pairs: Sequence[tuple[int, int]]) -> int:
    """Doc 04 step 2, exactly: `(n*Sxy - Sx*Sy) * 10000 // (n*Sxx - Sx*Sx)`.

    Scaled by 10000 so the sub-unit slopes that matter most survive — "one touch fewer every three
    months" is a slope of -1/3, and an unscaled integer division would report it as zero. Multiply
    before dividing, which is doc 04's fourth failure mode.

    The denominator is `n * sum(x^2) - sum(x)^2`, which is zero only when every known point sits
    at the same period index. Two points cannot share an index — the index IS the period — so this
    is unreachable above one known point, and one known point cannot get here at all (`n >= 4`).
    """
    n = len(pairs)
    sx = sum(x for x, _ in pairs)
    sy = sum(y for _, y in pairs)
    sxx = sum(x * x for x, _ in pairs)
    sxy = sum(x * y for x, y in pairs)
    return _idiv((n * sxy - sx * sy) * 10_000, n * sxx - sx * sx)


def _robust_slope_scaled(pairs: Sequence[tuple[int, int]]) -> int:
    """The median of every pairwise slope, scaled by 10000. Theil-Sen, in integers.

    **This is the estimator the direction is read off, and it exists because doc 04's own
    acceptance list contains a row least squares cannot satisfy.** Take the doc's case: nine
    readings of 100 and a tenth of 100000. Least squares returns a slope of +5449 per period on a
    base of 10090 — a normalised +5400 bp, eleven times the direction threshold — and the series
    is reported RISING on the strength of one number. That is not a tuning problem; squared error
    is *defined* to let one distant point dominate.

    The median of the 45 pairwise slopes for the same series is 0: thirty-six of the pairs are
    flat and only nine touch the outlier, so the outlier moves the answer by nine ranks and not at
    all in value. One point can move a least-squares line arbitrarily far; it can move a median
    by one rank. Both are computed and both must agree before a direction is claimed.

    O(n^2), which is 5356 pairs at the retention cap of 104 points and typically 66 at the twelve
    U3 reads. There is no series in this system where that is a cost worth trading honesty for.
    """
    slopes = [_idiv((later_y - early_y) * 10_000, later_x - early_x)
              for index, (early_x, early_y) in enumerate(pairs)
              for later_x, later_y in pairs[index + 1:]]
    return _lower_median(slopes) if slopes else 0


def _base_value(pairs: Sequence[tuple[int, int]]) -> int:
    """Doc 04 step 3's denominator: the mean MAGNITUDE of the known readings, floored at 1.

    **Step 3 is the one people skip and it is what makes the word "declining" comparable across
    metrics.** A drop of five means nothing on a base of 5000 and everything on a base of 8; an
    absolute slope shared between `engagement.touch_count` and `deal.value_minor_units` is two
    incomparable numbers wearing one field name.

    Magnitude rather than the signed mean, which is a deliberate departure from `max(mean, 1)` as
    written: a differenced or delta metric runs negative, its signed mean is negative, `max(.., 1)`
    collapses the base to 1, and every slope on it normalises to the clamp rail. The magnitude
    mean is the same number on every non-negative series — which is all twelve registered metrics
    — and is the scale of the series on the rest.

    The floor at 1 is what makes an all-zero series return FLAT instead of a `ZeroDivisionError`.
    """
    return max(_idiv(sum(abs(value) for _, value in pairs), len(pairs)), 1)


def _direction(robust_relative_bp: int, ls_relative_bp: int) -> TrendDirection:
    """Doc 04 step 4, over BOTH normalised slopes. Disagreement is FLAT.

    Requiring agreement is a one-way ratchet toward refusal: it can only ever turn a direction
    into FLAT, never manufacture one. That is the correct asymmetry — a missed decline costs a
    card that could have been shown, and a fabricated decline is a false churn alarm about a real
    customer who is fine.
    """
    if robust_relative_bp > DIRECTION_THRESHOLD_BP and ls_relative_bp > DIRECTION_THRESHOLD_BP:
        return TrendDirection.RISING
    if robust_relative_bp < -DIRECTION_THRESHOLD_BP and ls_relative_bp < -DIRECTION_THRESHOLD_BP:
        return TrendDirection.DECLINING
    return TrendDirection.FLAT


def _streak(series: Sequence[MetricPoint], direction: TrendDirection) -> int:
    """Doc 04 step 5 — consecutive PERIODS moving in the trend's direction, counted from the end.

    Counted in points rather than in steps, which is what doc 09's "a monotonic decline over 6
    points -> streak=6" asks for: five consecutive down-moves are six periods of decline.

    **A GAP ENDS THE RUN.** Two known readings either side of a hole are not consecutive periods,
    and calling them one run is the interpolation this module refuses, moved from the value into
    the count. Trailing gaps are skipped rather than zeroing the run — the run is a true statement
    about the series that ends at the last period we actually read.

    FLAT reports 0. There is no direction to move in, so any number here would be a run of
    something the field does not name; a reader who wants "steady for six months" has
    `point_count` and `coverage_ratio_bp`, which say it without inventing a unit.
    """
    if direction not in DIRECTIONAL:
        return 0
    rising = direction is TrendDirection.RISING
    index = len(series) - 1
    while index >= 0 and not series[index].known:
        index -= 1
    if index < 0:
        return 0
    run = 1
    while index >= 1 and series[index - 1].known:
        later, earlier = series[index].value_bp, series[index - 1].value_bp
        if later is None or earlier is None:
            break
        if (later > earlier) is not rising or later == earlier:
            break
        run += 1
        index -= 1
    return run


def _dispersion_bp(pairs: Sequence[tuple[int, int]], slope_scaled: int, base: int) -> int:
    """Mean absolute residual around the least-squares line, as basis points of the base.

    This is the "residual_dispersion" term doc 04 names in step 6 and never defines. Mean absolute
    deviation rather than a standard deviation: a square root has no integer answer, and the
    absolute residual is the quantity a reader can check against the printed series.

    Everything stays multiplied by 10000 — `slope_scaled` already is — so the division into basis
    points of the base happens exactly once, at the end.
    """
    n = len(pairs)
    sx = sum(x for x, _ in pairs)
    sy = sum(y for _, y in pairs)
    intercept_scaled = _idiv(sy * 10_000 - slope_scaled * sx, n)
    total = sum(abs(value * 10_000 - (intercept_scaled + slope_scaled * index))
                for index, value in pairs)
    return _idiv(_idiv(total, n), base)


def _confidence_bp(*, point_count: int, coverage_ratio_bp: int, streak_periods: int,
                   dispersion_bp: int) -> int:
    """Doc 04 step 6: `f(point_count, coverage_ratio, streak_length, residual_dispersion)`, capped.

    Four components, each already in basis points, combined on fixed integer weights and then
    scaled INTO the cap rather than clipped at it. Scaling matters: a `min(x, 8000)` would make
    every well-supported trend report exactly 8000 and destroy the ordering between a twelve-point
    full-coverage series and a four-point one at the moment a ranker needs it most. Here the
    ceiling is reachable only by a series that is saturated on all four components at once, and
    `MAX_TREND_CONFIDENCE_BP` is structurally unexceedable — V-4 holds by construction, not by a
    check the next editor can move.

    The weights say what the doc says in prose: how much we saw (count, coverage) outweighs how
    tidy it looked (streak, fit), because a beautiful line through four points out of ten periods
    is the exact object the coverage floor exists to distrust.
    """
    count_bp = min(point_count, CONFIDENT_POINTS) * 10_000 // CONFIDENT_POINTS
    streak_bp = min(streak_periods, point_count) * 10_000 // max(point_count, 1)
    fit_bp = 10_000 - min(dispersion_bp, 10_000)
    combined = (3 * count_bp + 3 * coverage_ratio_bp + 2 * streak_bp + 2 * fit_bp) // 10
    return combined * MAX_TREND_CONFIDENCE_BP // 10_000


def _refusal(series: Sequence[MetricPoint], metric: str, direction: TrendDirection,
             coverage_ratio_bp: int, point_count: int) -> Trend:
    """A refusal, carrying its receipt and nothing else.

    No confidence and no streak, which the contract enforces and which is the point: a number
    attached to an answer we declined to give is a number a ranker will sort on. The evidence
    points still travel, so a card that wants to say "we cannot see enough of this" can show
    exactly which periods it could not see.
    """
    return Trend(metric=metric, direction=direction, relative_slope_bp=0, streak_periods=0,
                 point_count=point_count, coverage_ratio_bp=coverage_ratio_bp,
                 trend_confidence_bp=0, evidence_points=tuple(series))


def compute_trend(series: Sequence[MetricPoint], *,
                  min_points: int = MIN_TREND_POINTS) -> Trend:
    """Doc 04's six ordered steps. A dense series in, one typed `Trend` out.

    PURE — no database, no network, no clock, no model. `eval_time` does not appear because
    nothing here needs one: the series already carries the periods it describes, and a function
    that read a clock would give two different answers for one stored series depending on when it
    was asked.

    `series` must be DENSE — every period in range present, gaps carried as `known=False` — which
    is exactly what `history.read_series` returns. A caller that filtered its gaps out first would
    hand this function a 100%-coverage series that is nothing of the kind, and the coverage floor
    would pass on a series it exists to refuse.

    Raises `ValueError` on an empty series rather than returning a refusal: `Trend` requires its
    evidence points, an empty series has none, and "no trend, no receipt" is a caller bug (asking
    about a period range that does not exist) rather than a fact about the tenant's data.
    """
    points = tuple(series)
    if not points:
        raise ValueError(
            "compute_trend needs a series — a trend with no evidence points is a claim with no "
            "receipt, and there is no honest direction to return for a range that holds nothing")
    if isinstance(min_points, bool) or not isinstance(min_points, int):
        raise TypeError("min_points must be an integer")
    if min_points < MIN_TREND_POINTS:
        raise ValueError(
            f"min_points cannot be lowered below {MIN_TREND_POINTS} — V-5 is a contract rule, and "
            "under four points there is no series, only two readings and a line drawn between them")

    metric = points[0].metric
    pairs = _known_pairs(points)
    point_count = len(pairs)
    coverage_ratio_bp = point_count * 10_000 // len(points)

    # STEP 1 · COVERAGE. Refuses in the doc's order: too little history is a different sentence
    # from too many holes, and reporting the second when the first is true would tell a tenant to
    # connect a source when the truth is that we have only been watching for three weeks.
    if point_count < min_points:
        return _refusal(points, metric, TrendDirection.INSUFFICIENT_HISTORY,
                        coverage_ratio_bp, point_count)
    if coverage_ratio_bp < COVERAGE_FLOOR_BP:
        return _refusal(points, metric, TrendDirection.INSUFFICIENT_COVERAGE,
                        coverage_ratio_bp, point_count)

    # STEPS 2-4 · SLOPE, NORMALISE, DIRECTION. Both slopes, both normalised against the same base.
    base = _base_value(pairs)
    ls_slope_scaled = _ls_slope_scaled(pairs)
    robust_slope_scaled = _robust_slope_scaled(pairs)
    relative_slope_bp = _clamp_bp(_idiv(robust_slope_scaled, base))
    ls_relative_bp = _clamp_bp(_idiv(ls_slope_scaled, base))
    direction = _direction(relative_slope_bp, ls_relative_bp)

    # STEPS 5-6 · STREAK and CONFIDENCE.
    streak_periods = _streak(points, direction)
    confidence_bp = _confidence_bp(
        point_count=point_count, coverage_ratio_bp=coverage_ratio_bp,
        streak_periods=streak_periods,
        dispersion_bp=_dispersion_bp(pairs, ls_slope_scaled, base))
    return Trend(metric=metric, direction=direction,
                 # FLAT reports the measured drift; only a DIRECTIONAL trend is allowed to keep a
                 # signed slope the card will read as a claim, and the contract refuses the two
                 # mismatched combinations outright.
                 relative_slope_bp=relative_slope_bp, streak_periods=streak_periods,
                 point_count=point_count, coverage_ratio_bp=coverage_ratio_bp,
                 trend_confidence_bp=confidence_bp, evidence_points=points)


