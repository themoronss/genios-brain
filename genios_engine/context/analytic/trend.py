"""L2.4.3 · the TREND COMPUTER (BLG-08) — the first function in GeniOS that can say "declining".

Three units live here and they are one pipeline:

* **U1 `compute_trend`** — a dense series in, a typed `Trend` out. Pure: no database, no network,
  no clock, no model. Integer arithmetic end to end.
* **U2 `find_changepoint`** — *"since March"* rather than *"declining"*. The longest suffix whose
  direction differs from the prefix, both segments held to the same four-point floor.
* **U3 `refresh_trend_facts`** — writes the answer back as `derived.trend.<metric>` on the node so
  L3 and L4 read it like any other fact. Called from `context/runner.process_pending`, which is
  the sweep both API sync routes and the upload route already run.

**WHY THE MEASUREMENT REFUSES TO USE A MODEL.** A trend is a comparison of a business against its
own past, and a comparison needs a stable instrument. If March's reading and September's reading
came from a language model, a disagreement between them could be attributed neither to the
business nor to the model — which makes the reading worthless in the only situation where anyone
cares. Every number below is an integer computed by a formula a reader can re-run by hand.

**THE TWO REFUSALS ARE THE PRODUCT.** `INSUFFICIENT_HISTORY` and `INSUFFICIENT_COVERAGE` are
return values, not errors. Doc 04 names "a coverage gap read as decline" as *the worst output this
group can produce* — a false churn alarm about a real customer, generated by the tenant connecting
one fewer mailbox. A gap is never a zero here, never interpolated, and it counts AGAINST the
coverage ratio rather than silently improving it.

**TWO SLOPES, AND WHY** (see `_ls_slope_scaled` / `_robust_slope_scaled`). Doc 04 step 2 prescribes
integer least squares, and doc 04's own acceptance list also requires that *"a single huge outlier
at the end does not flip a 10-point flat series to RISING"*. Those two requirements contradict
each other: least squares is defined by squared error, so one reading a thousand times the base
dominates the fit completely — the arithmetic is worked through in `_robust_slope_scaled`. Both
are therefore computed. The **median of pairwise slopes** (Theil-Sen, integer, O(n^2) over a
series the retention cap holds to 104 points) is the reported estimator, and the least-squares
slope must AGREE with it in sign and magnitude before any direction is claimed. A single point can
move the least-squares line arbitrarily far; it can move a median by one rank.
"""

