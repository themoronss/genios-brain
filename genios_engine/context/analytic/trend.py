#: Doc 04 step 4. A move of less than 5% of the base per period is not a direction, it is noise
#: with a sign. Applied to the NORMALISED slope, never to the raw one — see step 3.
DIRECTION_THRESHOLD_BP = 500

#: Doc 04 step 1. A series more than 40% holes cannot support a trend claim: the fit would be
#: describing the periods we happened to observe, and the reader has no way to see that from the
#: word "declining". Compared with `<`, so a series exactly 60% known still answers.
COVERAGE_FLOOR_BP = 6_000

#: The point count at which the count component of confidence saturates. Twelve monthly readings
#: is a year; nothing beyond it makes the extrapolation more honest, and the cap is what stops a
#: 104-point series from reaching confidence a four-point one is denied.
CONFIDENT_POINTS = 12

#: How far back U3 reads when it refreshes the facts. Twelve periods is a year of months or a
#: quarter of weeks, it is three times BLG-08's floor, and it bounds the dense read: the series
#: materialised per (node, metric) is twelve `MetricPoint`s, not the whole retention window.
TREND_WINDOW_PERIODS = 12

#: U3's per-sweep ceiling on (node, metric) pairs. The write itself is bounded by construction —
#: one version-keyed row per pair, overwritten forever — but the READ is one dense series each,
#: and an org with 50k nodes would otherwise turn one sweep into 50k series reads. Deterministic
#: tail: the pairs are ordered, so the same sweep truncates at the same place and the next sweep
#: (after the sampler has moved the series) covers what this one did.
MAX_TREND_FACTS_PER_SWEEP = 2_000

#: The `graph_facts.field` prefix. `derived.*` is the namespace every computed fact in L2 writes
#: into (`derived.engagement`, `derived.stage`), so L3's readers already walk it.
TREND_FACT_PREFIX = "derived.trend."

#: `graph_facts.value_type` for the object U3 writes. The value is a JSON document — direction,
#: strength, coverage and the series pointer — because a trend split across six scalar facts is
#: six rows a reader has to re-assemble and any one of which can go stale on its own.
TREND_VALUE_TYPE = "json"


# =================================================================================================
# INTEGER ARITHMETIC. No float appears in this module, including as an intermediate.
# =================================================================================================

def _idiv(numerator: int, denominator: int) -> int:
    """Integer division that TRUNCATES TOWARD ZERO, unlike Python's `//`.

    `//` floors, so `-1 // 3` is `-1` while `1 // 3` is `0`. On a slope that asymmetry is not
    cosmetic: it biases every small negative move one unit further from zero than the mirror-image
    positive move, so a series and its negation do not produce mirror-image trends, and at the
    `DIRECTION_THRESHOLD_BP` boundary the two signs cross at different magnitudes. Truncation
    toward zero makes `compute_trend(-series)` the exact negation of `compute_trend(series)`,
    which is the property the sign-inversion mutation test rests on.
    """
    if denominator == 0:
        raise ZeroDivisionError("integer division by zero in the trend arithmetic")
    quotient = abs(numerator) // abs(denominator)
    return -quotient if (numerator < 0) != (denominator < 0) else quotient


def _clamp_bp(value: int) -> int:
    """Hold a normalised slope inside the contract's signed basis-point range.

    `Trend.relative_slope_bp` is validated by `require_signed_bp` at -10000..10000, and a series
    that halves every period legitimately computes past that. Clamping rather than raising: a
    metric falling faster than its own base per period is a real reading, and the rail is the
    honest rendering of "off the scale in this direction" — refusing to build the object would
    turn the most extreme decline in the tenant's data into an exception on the sweep.
    """
    return max(-10_000, min(10_000, value))


def _lower_median(values: Sequence[int]) -> int:
    """The lower median of an already-sortable list. Deterministic on an even count.

    The lower of the two middles rather than their mean: the mean of two integers is not an
    integer, and rounding it would put a value in the output that is not one of the pairwise
    slopes actually observed.
    """
    ordered = sorted(values)
    return ordered[(len(ordered) - 1) // 2]


