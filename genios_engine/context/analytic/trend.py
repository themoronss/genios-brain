# U3 · THE TREND AS A GRAPH FACT — the wiring, and the reason the other two units are reachable
# =================================================================================================

def trend_fact_field(metric: str) -> str:
    """`derived.trend.<metric>` — the `graph_facts.field` a trend is written under.

    One field per metric rather than one `derived.trend` blob per node: L3's readers select on
    `field`, and a blob would make "is engagement declining" a read of every trend the node has.
    """
    return f"{TREND_FACT_PREFIX}{require_identifier(metric, 'metric')}"


def trend_fact_value(trend: Trend, changepoint: Changepoint | None = None) -> dict[str, Any]:
    """The JSON body of the fact: the answer, its strength, and the pointer back to the series.

    The pointer is `(subject_node_id, metric, first_period, last_period)` — `metric_history`'s
    primary key minus the ambient tenant — so "where did this decline come from" is a query a
    reader can actually run, rather than a claim that bottoms out in a card. The evidence VALUES
    are deliberately not copied in: they are already rows in a table built to be read across time,
    and a second copy in `graph_facts` is a second thing to keep in step with retention.
    """
    body: dict[str, Any] = {
        "metric": trend.metric,
        "direction": trend.direction.value,
        "relative_slope_bp": trend.relative_slope_bp,
        "streak_periods": trend.streak_periods,
        "point_count": trend.point_count,
        "coverage_ratio_bp": trend.coverage_ratio_bp,
        "trend_confidence_bp": trend.trend_confidence_bp,
        "series": {
            "subject_node_id": trend.evidence_points[0].subject_node_id,
            "metric": trend.metric,
            "unit": trend.evidence_points[0].unit.value,
            "first_period": trend.evidence_points[0].observed_at.isoformat(),
            "last_period": trend.evidence_points[-1].observed_at.isoformat(),
            "periods": len(trend.evidence_points),
        },
    }
    if changepoint is not None:
        body["changepoint"] = {"at": changepoint.at.isoformat(), "turned": changepoint.turned}
    return body


def _window_start(eval_time: datetime, grain: MetricGrain, periods: int) -> datetime:
    """The boundary `periods - 1` periods before `eval_time`'s period. No calendar library.

    Walks backwards through `period_start` for months so the month arithmetic is the store's own
    and a 31st never lands on a phantom boundary; weeks are seven days, exactly as
    `history.next_period` adds them.
    """
    start = period_start(eval_time, grain)
    if grain is MetricGrain.WEEK:
        return start - timedelta(days=7 * (periods - 1))
    year, month = divmod(start.year * 12 + (start.month - 1) - (periods - 1), 12)
    return start.replace(year=year, month=month + 1, day=1)


def _trended_pairs(store, org_id: str, limit: int) -> list[tuple[str, str]]:
    """Every `(node, metric)` this org has history for, ordered, capped.

    Read off `metric_history` rather than off the node table: the sampler's policy has already
    decided which nodes and metrics are worth a series, and re-deriving that decision here would
    be a second copy of BLG-07 that can disagree with the first. A pair with no points cannot
    produce a trend anyway.
    """
    from sqlalchemy import text

    from genios_engine.context.analytic.history import HISTORY_TABLE

    with store.engine.connect() as conn:
        rows = conn.execute(text(
            f"select distinct subject_node_id, metric from {HISTORY_TABLE} where org_id = :o "
            "order by subject_node_id, metric limit :n"), {"o": org_id, "n": limit}).all()
    return [(row[0], row[1]) for row in rows]


def _write_trend_fact(conn, *, org_id: str, node_id: str, field_name: str, value: dict[str, Any],
                      now: datetime) -> None:
    """The version-keyed upsert every derived writer in L2 uses, and THE BOUNDING PROPERTY of U3.

    `graph_facts` is keyed on `fact_version_id`, so a recompute OVERWRITES its own row rather than
    appending one per sweep. That is not a detail here: `expertise_packages` reached 181 MB across
    345 rows and put this database into read-only, and the shape that did it was a lifecycle
    transition appending a row every time it ran. A trend is recomputed on every drain, so an
    appending writer would add one row per node per metric per sweep forever — which on an org
    with 5000 nodes and twelve metrics is 60000 rows a sweep. The deterministic version id makes a
    sweep that runs twice in one period write the same row twice, and hold the table at exactly
    one row per (node, metric) for the life of the tenant.

    No new table, so nothing is added to `api/account_routes._ORG_SCOPED_TABLES` — `graph_facts` is
    already on it, and these rows are erased with the tenant by the entry that is already there.
    """
    from sqlalchemy import text

    conn.execute(text(
        "insert into graph_facts (fact_version_id, fact_id, org_id, subject_node_id, "
        "field, value, value_type, status, authority_rank, confidence, occurred_at, "
        "valid_from, visibility_scope) values "
        "(:vid, :fid, :o, :n, :f, cast(:v as jsonb), :vt, 'active', 100, 0.9, :now, :now, 'org') "
        "on conflict (fact_version_id) do update set value = excluded.value, "
        "occurred_at = excluded.occurred_at, valid_from = excluded.valid_from"),
        {"vid": f"fv_trend_{node_id}_{field_name}", "fid": f"f_trend_{node_id}_{field_name}",
         "o": org_id, "n": node_id, "f": field_name,
         "v": json.dumps(value, default=str, sort_keys=True), "vt": TREND_VALUE_TYPE, "now": now})


def refresh_trend_facts(store, org_id: str, *, eval_time: datetime,
                        history: Any = None, registry: MetricRegistry | None = None,
                        window_periods: int = TREND_WINDOW_PERIODS,
                        limit: int = MAX_TREND_FACTS_PER_SWEEP) -> int:
    """U3 — recompute every trend this org has history for and write it back. Returns rows written.

    Called from `context/runner.process_pending`, immediately after the sampler that produced the
    points. Here rather than on a schedule for the reason the whole layer prefers: the Celery
    broker is a quota-limited Upstash instance, and the drain is the only thing that knows an org
    is active.

    **REFUSALS ARE WRITTEN TOO, and that is deliberate.** The cheap-looking alternative — write
    only RISING/DECLINING/FLAT — leaves last week's `DECLINING` sitting on a node whose series has
    since gone dark, which is the stale-fact fault: a card would keep citing a decline that the
    data no longer supports and nothing would ever retract it. Writing the refusal overwrites the
    same version-keyed row with "we cannot see enough of this", so the fact self-corrects on the
    next sweep and the row count does not move.

    `eval_time` is a parameter with no default and no fallback clock. It is the `as_at` horizon of
    every read as well as the end of every window, so a trend computed for a past instant uses
    only what was known then — which is the entire reason the history store records `sampled_at`
    separately from `observed_at`.
    """
    from genios_engine.context.analytic.sampler import resolve_history_store, sampler_registry

    at = require_aware(eval_time, "eval_time")
    registry = registry or sampler_registry()
    history = history if history is not None else resolve_history_store(store)

    written = 0
    facts: list[tuple[str, str, dict[str, Any]]] = []
    for node_id, metric in _trended_pairs(store, org_id, limit):
        definition: MetricDefinition | None = registry.get(metric)
        if definition is None:
            continue          # written under a name this process does not define; not ours to read
        series = history.read_series(
            org_id, node_id, metric,
            since=_window_start(at, definition.grain, window_periods), until=at, as_at=at)
        if not series:
            continue
        trend = compute_trend(series)
        changepoint = None if trend.direction in NON_ANSWERS else find_changepoint(series)
        facts.append((node_id, trend_fact_field(metric), trend_fact_value(trend, changepoint)))

    if not facts:
        return 0
    with store.engine.begin() as conn:
        for node_id, field_name, value in facts:
            _write_trend_fact(conn, org_id=org_id, node_id=node_id, field_name=field_name,
                              value=value, now=at)
            written += 1
    return written


