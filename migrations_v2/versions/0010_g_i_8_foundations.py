def _create_audit_log(is_pg: bool) -> None:
    if is_pg:
        op.execute(
            """
            CREATE TABLE audit_log (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY,
                org_id VARCHAR(64) NOT NULL,
                actor_type VARCHAR(16) NOT NULL,
                actor_id VARCHAR(128) NOT NULL,
                action VARCHAR(64) NOT NULL,
                target_type VARCHAR(64) NOT NULL,
                target_id VARCHAR(128) NOT NULL,
                metadata_jsonb JSONB NOT NULL DEFAULT '{}'::jsonb,
                timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                PRIMARY KEY (id, timestamp)
            ) PARTITION BY RANGE (timestamp);
            """
        )
        op.execute(
            "CREATE INDEX ix_audit_org_ts ON audit_log (org_id, timestamp);"
        )
        op.execute(
            "CREATE INDEX ix_audit_org_action_ts "
            "ON audit_log (org_id, action, timestamp);"
        )
        op.execute("CREATE INDEX ix_audit_target ON audit_log (target_type, target_id);")
        return

    op.create_table(
        "audit_log",
        sa.Column("id", sa.Integer, sa.Identity(always=False), primary_key=True),
        sa.Column("org_id", sa.String(64), nullable=False),
        sa.Column("actor_type", sa.String(16), nullable=False),
        sa.Column("actor_id", sa.String(128), nullable=False),
        sa.Column("action", sa.String(64), nullable=False),
        sa.Column("target_type", sa.String(64), nullable=False),
        sa.Column("target_id", sa.String(128), nullable=False),
        sa.Column("metadata_jsonb", sa.JSON, nullable=False, server_default="{}"),
        sa.Column(
            "timestamp",
            sa.DateTime(timezone=True),
            nullable=False,
            primary_key=True,
            server_default=sa.func.now(),
        ),
    )
    op.create_index("ix_audit_org_ts", "audit_log", ["org_id", "timestamp"])
    op.create_index(
        "ix_audit_org_action_ts", "audit_log", ["org_id", "action", "timestamp"]
    )
    op.create_index("ix_audit_target", "audit_log", ["target_type", "target_id"])


