def _install_audit_immutability_trigger() -> None:
    op.execute(
        """
        CREATE OR REPLACE FUNCTION audit_log_block_modify()
        RETURNS trigger AS $$
        BEGIN
            RAISE EXCEPTION 'audit_log is append-only (UPDATE/DELETE blocked)';
        END;
        $$ LANGUAGE plpgsql;
        """
    )
    op.execute(
        """
        CREATE TRIGGER trg_audit_log_immutable
        BEFORE UPDATE OR DELETE ON audit_log
        FOR EACH ROW EXECUTE FUNCTION audit_log_block_modify();
        """
    )


def _create_initial_partitions(bind: Any) -> None:
    """Pre-create PARTITION_LOOKAHEAD_MONTHS monthly partitions from current month."""
    now = datetime.utcnow()
    year, month = now.year, now.month
    for _ in range(PARTITION_LOOKAHEAD_MONTHS):
        start = f"{year:04d}-{month:02d}-01"
        if month == 12:
            n_year, n_month = year + 1, 1
        else:
            n_year, n_month = year, month + 1
        end = f"{n_year:04d}-{n_month:02d}-01"
        part_name = f"audit_log_{year:04d}{month:02d}"
        op.execute(
            f"CREATE TABLE IF NOT EXISTS {part_name} "
            f"PARTITION OF audit_log FOR VALUES FROM ('{start}') TO ('{end}');"
        )
        year, month = n_year, n_month
